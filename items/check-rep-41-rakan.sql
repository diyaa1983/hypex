SELECT COUNT(*) AS excel_rakan FROM tmp_rakan;
SELECT COUNT(DISTINCT c.id) AS linked_rakan
FROM crm_customer c
JOIN crm_sales_rep r ON r.id = c.sales_rep_id AND r.code = '41'
JOIN tmp_rakan t ON (
  TRIM(c.code) = t.cust_code
  OR TRIM(IFNULL(c.oracle_key, '')) = t.cust_code
  OR REGEXP_REPLACE(TRIM(c.code), '[^0-9]', '') = t.cust_code
);
SELECT t.cust_code AS missing_in_hypex
FROM tmp_rakan t
WHERE NOT EXISTS (
  SELECT 1 FROM crm_customer c
  WHERE TRIM(c.code) = t.cust_code
     OR TRIM(IFNULL(c.oracle_key, '')) = t.cust_code
     OR REGEXP_REPLACE(TRIM(c.code), '[^0-9]', '') = t.cust_code
)
ORDER BY t.cust_code;
