-- 4) الفئات المستخدمة فعلياً مع المواد في MASCARD
SELECT DISTINCT CAT, COUNT(*) AS CNT
FROM MAS.MASCARD
GROUP BY CAT
ORDER BY CAT;

-- 5) الفئات التي لها رصيد تشغيلات (BALANCE) — مثل Forms
SELECT DISTINCT CAT, COUNT(*) AS CNT
FROM MAS.BALANCE
WHERE STORE = 4
  AND NVL(QTY_OH, 0) > 0
GROUP BY CAT
ORDER BY CAT;

-- 6) فئة المادتين في الطلب CO022 (600018 و 200008)
SELECT 'MASCARD' AS SRC, TRIM(TO_CHAR(ITEM)) AS ITEM, TRIM(TO_CHAR(CAT)) AS CAT, IDESC
FROM MAS.MASCARD
WHERE TRIM(TO_CHAR(ITEM)) IN ('600018','200008')
   OR LTRIM(TRIM(TO_CHAR(ITEM)),'0') IN ('600018','200008');

SELECT 'BALANCE' AS SRC, TRIM(TO_CHAR(ITEM)) AS ITEM, TRIM(TO_CHAR(CAT)) AS CAT,
       TRIM(TO_CHAR(BATCH)) AS BATCH, QTY_OH
FROM MAS.BALANCE
WHERE STORE = 4
  AND NVL(QTY_OH,0) > 0
  AND (TRIM(TO_CHAR(ITEM)) IN ('600018','200008')
    OR LTRIM(TRIM(TO_CHAR(ITEM)),'0') IN ('600018','200008'))
ORDER BY ITEM, CAT, BATCH;

-- 7) إن وُجد جدول أسماء الفئات — ابحث عن أعمدة NAME + CAT
SELECT OWNER, TABLE_NAME, COLUMN_NAME
FROM ALL_TAB_COLUMNS
WHERE OWNER IN ('MAS','ACCINV')
  AND UPPER(COLUMN_NAME) IN ('CAT','CAT_NO','CAT_NUM','GROUP_CODE','GROUP_NO')
  AND TABLE_NAME IN (
      SELECT TABLE_NAME FROM ALL_TAB_COLUMNS t2
      WHERE t2.OWNER = ALL_TAB_COLUMNS.OWNER
        AND UPPER(t2.COLUMN_NAME) IN ('NAME','NAME_A','NAME_AR','CAT_NAME','GROUP_NAME','IDESC','DESCR','DESCRIPTION')
  )
ORDER BY OWNER, TABLE_NAME;
