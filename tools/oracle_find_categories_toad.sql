-- 1) كل الجداول/الأعمدة التي اسمها يشبه فئة
SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM ALL_TAB_COLUMNS
WHERE OWNER IN ('MAS', 'ACCINV')
  AND (
       UPPER(COLUMN_NAME) IN ('CAT','CATE','CATEGORY','CAT_NO','CAT_NUM','CAT_CODE','GROUP_NO','GRP','GROUP_CODE','GROUP_NAME','CAT_NAME','IDESC_CAT')
    OR UPPER(COLUMN_NAME) LIKE '%CAT%'
    OR UPPER(COLUMN_NAME) LIKE '%GROUP%'
    OR UPPER(TABLE_NAME) LIKE '%CAT%'
    OR UPPER(TABLE_NAME) LIKE '%GROUP%'
  )
ORDER BY OWNER, TABLE_NAME, COLUMN_ID;

-- 2) جداول مرشّحة لأسماء الفئات (غالباً جداول رئيسية)
SELECT OWNER, TABLE_NAME
FROM ALL_TABLES
WHERE OWNER IN ('MAS', 'ACCINV')
  AND (
       UPPER(TABLE_NAME) LIKE '%CAT%'
    OR UPPER(TABLE_NAME) LIKE '%GROUP%'
    OR UPPER(TABLE_NAME) IN ('ITEM_GROUP','ITEMGROUP','CATEGORIES','CATEGORY','CAT','MASCARD','GROUPS')
  )
ORDER BY OWNER, TABLE_NAME;

