-- كشف كيف يظهر السند 24985 في Forms كـ «مبيعات فواتير نقدية»
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';

-- أ) بنود السند + مندوب العميل + وصف الدليل
SELECT v.VOD_NUM, v.VOD_FLAG, v.VOD_TYPE, v.VOD_SIDE, v.VOD_DATE,
       v.VOD_ACC, ROUND(ABS(v.VOD_AMOUNT),3) AMT,
       g.ACC_DESC, c.CUS_SALESMAN, c.CUS_TITLE
  FROM ACCINV.GLVODMF v
  LEFT JOIN ACCINV.GLACTMF g ON TRIM(TO_CHAR(g.ACC_NUM))=TRIM(TO_CHAR(v.VOD_ACC))
  LEFT JOIN ACCINV.CUSTOMER c ON TRIM(TO_CHAR(c.CUS_NUM))=TRIM(TO_CHAR(v.VOD_ACC))
 WHERE v.VOD_NUM = 24985
 ORDER BY v.VOD_SIDE, v.VOD_ACC;

-- ب) أعمدة البيان
SELECT COLUMN_NAME FROM ALL_TAB_COLUMNS
 WHERE OWNER='ACCINV' AND TABLE_NAME='GLVODMF'
   AND REGEXP_LIKE(COLUMN_NAME,'REMARK|DESC|NOTE|TYPE|FLAG','i')
 ORDER BY 1;

-- ج) DAILY / MASTER لنفس الرقم
SELECT 'DAILY' S, d.V_NUM, d.TYPE, d.MAN_NUM, d.VDATE, d.CUST_ACC
  FROM MAS.DAILY d WHERE d.V_NUM=24985 AND ROWNUM<=10
UNION ALL
SELECT 'MASTER', m.V_NUM, NULL, m.MAN_NUM, NULL, NULL
  FROM MAS.MASTER_D m WHERE m.V_NUM=24985 AND ROWNUM<=5;
