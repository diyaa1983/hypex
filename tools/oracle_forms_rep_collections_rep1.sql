-- كيف يرتبط السند 24985 بالمندوب 3؟
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';

SELECT 'VOD_LINE' AS SRC, v.VOD_NUM, v.VOD_ACC, v.VOD_FLAG, v.VOD_SIDE,
       ROUND(ABS(v.VOD_AMOUNT),3) AMT, g.ACC_DESC, c.CUS_SALESMAN MAN
  FROM ACCINV.GLVODMF v
  LEFT JOIN ACCINV.GLACTMF g ON TRIM(TO_CHAR(g.ACC_NUM))=TRIM(TO_CHAR(v.VOD_ACC))
  LEFT JOIN ACCINV.CUSTOMER c ON TRIM(TO_CHAR(c.CUS_NUM))=TRIM(TO_CHAR(v.VOD_ACC))
 WHERE v.VOD_NUM = 24985
UNION ALL
SELECT 'SAME_VOD_CUS', v.VOD_NUM, v.VOD_ACC, v.VOD_FLAG, v.VOD_SIDE,
       ROUND(ABS(v.VOD_AMOUNT),3), c.CUS_TITLE, c.CUS_SALESMAN
  FROM ACCINV.GLVODMF v
  JOIN ACCINV.CUSTOMER c ON TRIM(TO_CHAR(c.CUS_NUM))=TRIM(TO_CHAR(v.VOD_ACC))
 WHERE v.VOD_NUM = 24985 AND NVL(c.CUS_SALESMAN,0) > 0
UNION ALL
SELECT 'DAILY', d.V_NUM, TO_CHAR(d.CUST_ACC), d.TYPE, NULL,
       NULL, NULL, d.MAN_NUM
  FROM MAS.DAILY d WHERE d.V_NUM = 24985 AND NVL(d.MAN_NUM,0) > 0 AND ROWNUM <= 5
UNION ALL
SELECT 'MASTER_D', m.V_NUM, NULL, NULL, NULL, NULL, NULL, m.MAN_NUM
  FROM MAS.MASTER_D m WHERE m.V_NUM = 24985 AND NVL(m.MAN_NUM,0) > 0 AND ROWNUM <= 5;
