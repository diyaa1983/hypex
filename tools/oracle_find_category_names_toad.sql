-- د) هل يوجد وصف للفئة داخل MASCARD؟
SELECT COLUMN_NAME, DATA_TYPE
FROM ALL_TAB_COLUMNS
WHERE OWNER='MAS' AND TABLE_NAME='MASCARD'
ORDER BY COLUMN_ID;

-- هـ) كل CAT مع عدد المواد (للتحقق)
SELECT TRIM(TO_CHAR(CAT)) AS CAT, COUNT(*) AS CNT
FROM MAS.MASCARD
GROUP BY TRIM(TO_CHAR(CAT))
ORDER BY TO_NUMBER(REGEXP_REPLACE(TRIM(TO_CHAR(CAT)),'[^0-9]',''));
